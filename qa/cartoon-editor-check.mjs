import {chromium} from 'playwright';
const b=await chromium.launch({channel:'msedge',headless:true});
const p=await b.newPage({viewport:{width:1440,height:1000}});
p.on('pageerror',e=>console.log('ERROR',e.message));
await p.goto('http://127.0.0.1:5188/?qa',{waitUntil:'domcontentloaded'});
await p.locator('[data-action=editAppearance]').first().click();
await p.locator('.av-preview-loading').waitFor({state:'hidden',timeout:30000});
await p.screenshot({path:'qa/cartoon-editor-default.png'});
await p.locator('[data-preset="0"]').click();await p.waitForTimeout(300);
await p.screenshot({path:'qa/cartoon-editor-preset0.png'});
await p.locator('[data-category=body]').click();await p.locator('[data-view=full]').click();
console.log('body controls',await p.locator('[data-range=bodyRatio]').count());
await p.screenshot({path:'qa/cartoon-editor-body.png'});
await p.setViewportSize({width:390,height:844});await p.waitForTimeout(200);
await p.screenshot({path:'qa/cartoon-editor-mobile-body.png'});
await p.locator('[data-view=face]').click();await p.locator('[data-category=face]').click();
await p.screenshot({path:'qa/cartoon-editor-mobile-face.png'});
console.log(await p.locator('.av-style-picker').innerText());
await b.close();
