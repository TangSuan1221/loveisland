import {chromium} from 'playwright';
import {readFileSync,writeFileSync,readdirSync,existsSync} from 'node:fs';
import {createHash} from 'node:crypto';
import assert from 'node:assert/strict';
const round=process.argv[2];assert.match(round||'',/^[a-z0-9-]+$/,'supply a fresh evidence label');
const root=`qa/avatar-studio-${round}`;
for(const ext of ['.png','.json'])assert.ok(!existsSync(root+ext),'studio evidence is immutable');
const hash=bytes=>createHash('sha256').update(bytes).digest('hex');
const sourceState=()=>Object.fromEntries(readdirSync('src',{recursive:true}).filter(p=>/\.(js|css)$/.test(p)).map(p=>'src/'+p.replaceAll('\\','/')).sort().map(p=>[p,hash(readFileSync(p))]));
const sources=sourceState(),errors=[],updates=[],loaded={};
const browser=await chromium.launch({channel:'msedge',headless:true});
const context=await browser.newContext({viewport:{width:1680,height:1120},deviceScaleFactor:1,acceptDownloads:true});
const page=await context.newPage();page.setDefaultTimeout(30000);
page.on('pageerror',e=>errors.push(e.message));
page.on('websocket',socket=>socket.on('framereceived',({payload})=>{try{const event=JSON.parse(String(payload));if(['update','full-reload','error'].includes(event.type))updates.push(event);}catch{}}));
const reads=[];page.on('response',response=>{const path=new URL(response.url()).pathname.slice(1);if(/^src\/.*\.(js|css)$/.test(path))reads.push(response.body().then(bytes=>loaded[path]=hash(bytes)));});
const av=selector=>page.locator('.avatar-studio '+selector);
const settle=()=>page.evaluate(()=>new Promise(resolve=>{let count=0;const next=()=>++count===8?resolve():requestAnimationFrame(next);requestAnimationFrame(next);}));
try{
 assert.deepEqual(await context.storageState(),{cookies:[],origins:[]});
 await page.goto('http://127.0.0.1:5188/');
 await page.locator('[data-action="editAppearance"]').first().click();
 await av('.av-preview-loading').waitFor({state:'hidden'});
 await av('.av-preview-canvas canvas').waitFor();
 await av('[data-action="new"]').click();
 await av('.av-name').fill('金环赤发');
 await av('.av-presets button').filter({hasText:'金环赤发'}).click();
 await av('[data-category="eyes"]').click();
 await av('.av-eye-shape-editor svg').scrollIntoViewIfNeeded();await settle();
 const scroll=await av('.av-fields').evaluate(fields=>{const r=fields.getBoundingClientRect(),ys=[...fields.querySelectorAll('[data-eye-point]')].map(h=>new DOMPoint(0,0).matrixTransform(h.getScreenCTM()).y);return{x:r.x+r.width/2,y:r.y+r.height/2,delta:(Math.min(...ys)+Math.max(...ys))/2-r.y-r.height/2};});
 await page.mouse.move(scroll.x,scroll.y);await page.mouse.wheel(0,scroll.delta);await settle();
 assert.equal(await av('[data-eye-point]').count(),6);
 assert.doesNotMatch(await av('.av-status').innerText(),/失败/);
 const downloadEvent=page.waitForEvent('download');await av('[data-action="export"]').click();const download=await downloadEvent;
 const stream=await download.createReadStream(),chunks=[];for await(const c of stream)chunks.push(c);
 const draft=JSON.parse(Buffer.concat(chunks).toString('utf8'));
 const {ANIME_PRESETS}=await import('../src/avatar-anime.js');
 const {DEFAULT_APPEARANCE,normalizeAppearance}=await import('../src/avatar-schema.js');
 assert.deepEqual(draft.appearance,normalizeAppearance({...normalizeAppearance(DEFAULT_APPEARANCE),...ANIME_PRESETS.find(p=>p.name==='金环赤发').values}));
 await page.mouse.move(10,10);await settle();await Promise.all(reads);
 assert.deepEqual(sourceState(),sources);assert.deepEqual(errors,[]);assert.deepEqual(updates,[]);
 await page.screenshot({path:root+'.png',fullPage:true});
 assert.deepEqual(sourceState(),sources);assert.deepEqual(updates,[]);
 writeFileSync(root+'.json',JSON.stringify({round,capturedAt:new Date().toISOString(),url:page.url(),sourceFiles:sources,sourceFingerprint:hash(JSON.stringify(sources)),loadedModuleResponseHashes:loaded,screenshotSha256:hash(readFileSync(root+'.png')),draft,errors,updates,scope:'Actual public game entry; current production study selected and exported via UI. Isolated browser storage. Not a similarity certification.'},null,2));
 console.log('PASS: actual public studio, current full preset, six eye handles, frozen-source screenshot; no page errors or source reloads.');
}finally{await context.close();await browser.close();}
